@Composable
fun RolePermissionCard(title: String, themeColors: VisualThemePalette, items: List<String>) {
    Card(
        modifier = Modifier.fillMaxWidth(),
        colors = CardDefaults.cardColors(containerColor = themeColors.surface)
    ) {
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .padding(12.dp),
            verticalArrangement = Arrangement.spacedBy(6.dp)
        ) {
            Text(
                text = title,
                fontWeight = FontWeight.Bold,
                color = themeColors.accent,
                fontSize = 13.sp
            )
            items.forEach { item ->
                Text(
                    text = "• $item",
                    color = Color.LightGray,
                    fontSize = 11.sp
                )
            }
        }
    }
}
